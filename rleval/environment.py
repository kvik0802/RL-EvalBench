"""Gymnasium-compliant Reinforcement Learning Environment for ML Agent Training."""
from __future__ import annotations

from typing import Any, Dict, Optional, Tuple
import gymnasium as gym
from gymnasium import spaces

from rleval.schema import ExecutionResult, RewardSignal, TaskSpecification
from rleval.sandbox import ExecutionSandbox
from rleval.rewards import RewardEngine
from rleval.tasks import FRONTIER_TASKS


class MLEvalEnv(gym.Env):
    """
    OpenAI Gymnasium Environment for LLM/Coding Agents.
    The agent receives task specifications and outputs code patches/actions.
    The environment executes code in a sandbox, validates numerical correctness,
    and returns dense/sparse reward signals.
    """
    metadata = {"render_modes": ["human", "ansi"]}

    def __init__(self, tasks: list[TaskSpecification] | None = None):
        super().__init__()
        self.tasks = tasks or FRONTIER_TASKS
        self.current_task_idx = 0
        self.sandbox = ExecutionSandbox()
        self.reward_engine = RewardEngine()

        # Observation space: Task details
        self.observation_space = spaces.Dict({
            "task_id": spaces.Text(max_length=64),
            "category": spaces.Text(max_length=32),
            "prompt": spaces.Text(max_length=1024),
            "starter_code": spaces.Text(max_length=2048)
        })

        # Action space: Code string generated by agent
        self.action_space = spaces.Text(max_length=4096)
        self.current_task: Optional[TaskSpecification] = None

    def reset(self, seed: Optional[int] = None, options: Optional[Dict[str, Any]] = None) -> Tuple[Dict[str, Any], Dict[str, Any]]:
        super().reset(seed=seed)
        if options and "task_id" in options:
            self.current_task = next((t for t in self.tasks if t.task_id == options["task_id"]), self.tasks[0])
        else:
            self.current_task = self.tasks[self.current_task_idx % len(self.tasks)]
            self.current_task_idx += 1

        obs = {
            "task_id": self.current_task.task_id,
            "category": self.current_task.category,
            "prompt": self.current_task.prompt,
            "starter_code": self.current_task.starter_code
        }
        info = {"time_limit_sec": self.current_task.time_limit_sec, "memory_limit_mb": self.current_task.memory_limit_mb}
        return obs, info

    def step(self, action: str) -> Tuple[Dict[str, Any], float, bool, bool, Dict[str, Any]]:
        """
        Takes agent's submitted code action, executes in sandbox, returns reward.
        """
        assert self.current_task is not None, "Call reset() before step()"

        # Execute submission
        exec_result: ExecutionResult = self.sandbox.run_task(self.current_task, action)

        # Compute fine-grained RL reward
        reward_sig: RewardSignal = self.reward_engine.compute_reward(self.current_task, exec_result)

        terminated = True  # Single-turn task resolution
        truncated = False

        obs = {
            "task_id": self.current_task.task_id,
            "category": self.current_task.category,
            "status": exec_result.status
        }

        info = {
            "execution": exec_result.model_dump(),
            "reward_breakdown": reward_sig.breakdown,
            "passed": exec_result.status == "passed"
        }

        return obs, reward_sig.total_reward, terminated, truncated, info
